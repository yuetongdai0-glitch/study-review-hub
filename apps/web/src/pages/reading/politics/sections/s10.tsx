              <PointList>
                <li>声音由物体<b>振动</b>产生；传播<b>需要介质</b>，真空不能传声。</li>
                <li>三要素：<b>音调</b>（频率决定）、<b>响度</b>（振幅决定）、<b>音色</b>（材料与结构决定）。</li>
                <li>「闻其声知其人」＝音色；「震耳欲聋」＝响度；「男高音」＝音调。</li>
                <li>声速：固体 ＞ 液体 ＞ 气体（金属中最快）。</li>
                <li>人耳可听：<b>20 Hz ~ 20 kHz</b>；声音强度用<b>分贝（dB）</b>衡量。</li>
                <li><b>超声波</b>（＞20 kHz）：方向性好、能量集中——测距、清洗、碎石、杀菌、B 超、声呐。</li>
                <li><b>次声波</b>（＜20 Hz）：传播远、穿透强、可绕过障碍——灾害预警、核爆监测。</li>
                <li>声音的性质声音是由物体振动产生的声波。通常用音色、音调和响度来衡量声音的性质。音色的差别取决于发声体的不同材料和结构，音调的高低取决于发声体振动的频率，响度的大小取决于发声体振动的振幅。声音的强度用分贝（dB）来衡量。</li><li>声音性质的表现闻其声而知其人，原因在于每个人的音色不同。男高音、男中音、男低音的核心区别在于音调不同。震耳欲聋形容的是声音的响度很大。</li>
                <li>声音的传播声音的传播需要介质。在真空中，声音不能传播。常温下，声音在不同的介质中传播的速度不同，通常固体＞液体＞气体，且在金属介质中传播更快。</li>
                <li>声音的分类根据声音的频率，分为人耳可听声及超出听觉范围的声音。（1）可听声频率在20Hz~20kHz之间的声波，是人耳可以感知的。（2）超声波定义：频率高于20kHz的声波。</li><li>优点：方向性好，能量集中，对固体和液体穿透力强。缺点：传播距离短，受介质影响大，对气体穿透力差。应用：测距、测速、清洗、焊接、碎石、杀菌消毒、B超机、声呐等。（3）次声波定义：频率低于20Hz的声波。</li><li>优点：传播距离远，不易衰减或被吸收，在各种介质中穿透力都很强，能绕开障碍物发生衍射。缺点：方向性差，难以聚焦，容易和人体器官产生共振，对人体有很强的伤害性，危险时可致人死亡。应用：灾害预警，核爆监测等。</li>
              </PointList>
