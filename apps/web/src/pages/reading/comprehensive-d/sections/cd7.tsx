            <li><b>② 开展微格教学</b>——教师可以通过微格教学，进行<b>知识讲授与教学方法的训练</b>，<b>有重点地逐步提升</b>。特点：把复杂的课堂分解为导入、提问、讲解、板书、结束等单一技能，小规模、短时间、录像回放、同伴评议，聚焦一个技能反复训练。</li>
