        <div className="ex-q">材料：青年教师小许给自己定下规矩：每节课必须让所有学生都听懂，每次考试班级必须第一，否则就是自己无能。为此她每天工作到凌晨，最近常头痛、易怒，看到学生就烦。<b>问题：</b>请分析其压力来源并提出应对建议。</div>
