      <div className="kp">
        <div className="kp-t"><span className="dot"></span>家校沟通的四条原则：尊重 · 平等 · 客观 · 建设性（附保密）</div>
        <div className="kp-c">
          <ul>
            <li><b>尊重</b>——尊重家长的人格、文化背景、职业与生活处境，不用居高临下的「教育者」姿态训话；尊重家长对孩子的感情，不在其面前贬损孩子。作用：尊重是沟通的前提，被尊重才愿意合作。</li>
            <li><b>平等</b>——教师与家长是<b>育人伙伴</b>，不是上下级；教师有专业优势，家长有知情与参与权利；决策要协商，不能「通知式」下达。作用：平等才有真正的对话，才能听到家庭的真实情况。</li>
            <li><b>客观</b>——以事实为依据，<b>描述行为而不贴标签</b>：说「这周有三次作业没交」，不说「你这孩子就是懒」；说「课堂上多次离开座位」，不说「多动症吧」。评价对事不对人，不把个别行为扩大为人格判断。作用：客观才可信，贴标签只会引发辩解与对抗。</li>
            <li><b>建设性</b>——沟通的目的不是「告状」而是「解决」，每次沟通都应带出<b>具体、可操作、可检查</b>的办法，并约定后续反馈。作用：让家长带着方法回家，而不是带着情绪回家。</li>
            <li><b>保密</b>——学生的问题、家庭的隐私（家庭结构、经济状况、疾病、亲子冲突）仅在必要范围内知晓，不在办公室闲谈、不在班级群公开、不向其他家长透露。作用：泄露隐私会彻底摧毁信任，甚至引发法律与伦理问题。</li>
          </ul>
          <div className="mk"><b>【口诀】尊平客建密</b> —— 尊重、平等、客观、建设性、保密。</div>
          <div className="kt"><b>考察角度</b>：案例分析的评价类设问，可按「态度（尊重平等）—内容（客观有依据）—目的（建设性）—边界（保密）」四条逐一衡量教师行为。</div>
        </div>
      </div>
