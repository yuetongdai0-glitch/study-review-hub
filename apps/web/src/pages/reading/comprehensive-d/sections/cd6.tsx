        <div className="ex-q">材料：王老师习惯在放学时把家长拦在校门口谈问题，一谈就是一个小时，从作业说到坐姿，从坐姿说到家庭教育。家长起初还听，后来开始躲着走，孩子也越来越怕老师。<b>问题：</b>请分析问题所在。</div>
