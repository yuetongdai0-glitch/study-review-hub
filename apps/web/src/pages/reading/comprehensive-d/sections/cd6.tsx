      <div className="kp">
        <div className="kp-t"><span className="dot"></span>（二）3.（2）选择合适的沟通时机：时间、情绪、时长</div>
        <div className="kp-c">
          <ul>
            <li><b>① 要考虑家长的时间</b>——避开上班高峰、接送孩子的忙乱时段与深夜；提前预约并说明大概需要多久；紧急情况先电话简要告知，再约面谈。作用：家长在从容状态下才能听进建议，也体现对家长劳动的尊重。</li>
            <li><b>② 沟通中注意家长的情绪</b>——先观察、先倾听，家长激动时先共情安抚（「孩子这样您肯定着急」），待情绪平稳后再谈事实与方法；不在家长情绪失控时争辩、下结论；涉及双方冲突时先「冷处理」，另约时间。作用：情绪对立时信息无法传递，任何正确的方法都会被抵触。</li>
            <li><b>③ 控制谈话时间，避免时间过长，影响谈话效果</b>——一次沟通聚焦一两个核心问题，15—30 分钟为宜，结尾明确「下一步做什么、什么时候再反馈」。作用：时间过长易造成信息过载、重点模糊，家长疲惫后只记住情绪而记不住方法。</li>
          </ul>
          <div className="mk"><b>【口诀】看时间、看情绪、控时长</b> —— 时机三看。</div>
          <div className="kt"><b>考察角度</b>：案例分析题中「放学时堵在门口长谈一小时」「当着孩子面数落家长」均属时机不当。</div>
        </div>
      </div>
