            <li><b>① 重视对中等生的教育</b>。因为对中等生的教育不仅关系到<b>中等生自己的发展</b>，而且关系到<b>整个班级的进步</b>——中等生是班级的主体，其状态决定班风与整体学业水平；忽视中等生是班主任工作最常见的偏差。</li>
